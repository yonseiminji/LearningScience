// Move a built cache onto the current key scheme, without calling the model.
//
//   GEMINI_MODEL=… node scripts/rekey-prompt-cache.mjs <old-entries.js>
//
// A cache costs 108 real calls and about eight minutes. When the key scheme
// changes, the recorded answers are still the model's answers to the same
// questions — only the index moved. This rebuilds the index.
//
// It works by re-deriving the same job list (scripts/_cacheJobs.mjs), hashing
// each job's prompt both the way the old file was keyed and the way cacheKey
// does it now, and writing the value across. Matching every job means the
// mapping is complete; a job that does not match is reported rather than
// guessed at, because the alternative is a file that silently lost entries.
//
// Nothing here fabricates or edits an answer. Values are copied byte for byte.

import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')
const OUT = resolve(ROOT, 'api/_lib/cache/entries.js')

const { MODEL } = await import(resolve(ROOT, 'api/_lib/gemini.js'))
const { buildJobs } = await import(resolve(ROOT, 'scripts/_cacheJobs.mjs'))
const { cacheKey } = await import(resolve(ROOT, 'api/_lib/promptCache.js'))

const source = process.argv[2]
if (!source) {
  console.error('사용법: GEMINI_MODEL=… node scripts/rekey-prompt-cache.mjs <old-entries.js>')
  process.exit(1)
}
if (!process.env.GEMINI_MODEL) {
  console.error(`GEMINI_MODEL 을 그 캐시를 만들 때와 똑같이 주세요. 기본값은 ${MODEL} 입니다.`)
  process.exit(1)
}

// How keys were derived before chunk ids were flattened: the raw prompt, with
// the recording's own chunk ids still in it.
function legacyKey(systemInstruction, prompt, model) {
  return createHash('sha256')
    .update(`${model ?? ''}\u0000${systemInstruction ?? ''}\u0000${prompt ?? ''}`, 'utf8')
    .digest('hex')
    .slice(0, 24)
}

const old = (await import(`${resolve(source)}?v=${Date.now()}`)).default
const jobs = await buildJobs()

const moved = {}
const missing = []
const seen = new Set()

for (const job of jobs) {
  const { systemInstruction, prompt } = job.call
  const from = legacyKey(systemInstruction, prompt, MODEL)
  const to = cacheKey(systemInstruction, prompt, MODEL)
  if (!Object.hasOwn(old, from)) {
    missing.push(job.label)
    continue
  }
  moved[to] = old[from]
  seen.add(from)
}

const orphans = Object.keys(old).filter((key) => !seen.has(key))

const header = `// Generated by scripts/build-prompt-cache.mjs — do not edit by hand.
// Each value is the model's own answer to the exact prompt its key hashes.
// Regenerate after changing any prompt: the keys will all have moved.
// Re-keyed by scripts/rekey-prompt-cache.mjs; values untouched.

`

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, `${header}export default ${JSON.stringify(moved, null, 2)}\n`)

console.log(`\n  읽음 ${Object.keys(old).length}개 · 옮김 ${Object.keys(moved).length}개 · 작업 ${jobs.length}개`)
if (missing.length) {
  console.log(`\n  옛 파일에 없던 작업 ${missing.length}개 (실시간으로 갑니다):`)
  for (const label of missing.slice(0, 12)) console.log(`    ${label}`)
  if (missing.length > 12) console.log(`    … 그리고 ${missing.length - 12}개 더`)
}
if (orphans.length) {
  console.log(`\n  어느 작업과도 안 맞은 엔트리 ${orphans.length}개 — 버렸습니다 (프롬프트가 바뀐 흔적):`)
  for (const key of orphans.slice(0, 8)) console.log(`    ${key}`)
}
console.log(`  → ${OUT}`)
